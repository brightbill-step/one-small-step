let language = document.documentElement.lang === "fa" ? "fa" : "en";

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  const strings = copy[language];
  const isRtl = language === "fa";

  document.documentElement.lang = language;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";
  document.title = isRtl ? "یک قدم کوچک" : "One Small Step";

  document.querySelectorAll("[data-copy]").forEach((element) => {
    const key = element.dataset.copy;
    if (strings[key]) element.textContent = strings[key];
  });

  const languageButton = document.getElementById("language-button");
  languageButton.textContent = strings.language;
  languageButton.setAttribute("aria-label", strings.languageLabel);

  document.querySelectorAll(".voice-label").forEach((label) => {
    label.textContent = strings.voiceLabel;
  });
  document.querySelectorAll(".replies-title").forEach((heading) => {
    heading.textContent = strings.replyLabel;
  });

  try {
    localStorage.setItem("one-small-step-language", language);
  } catch (_) {}
}

document.getElementById("language-button").addEventListener("click", () => {
  applyLanguage(language === "en" ? "fa" : "en");
});

document.querySelectorAll("[data-scroll]").forEach((button) => {
  button.addEventListener("click", () => {
    document.getElementById(button.dataset.scroll)?.scrollIntoView({ behavior: "smooth" });
  });
});

function renderSteps(steps) {
  const wall = document.getElementById("step-wall");
  const empty = document.getElementById("wall-empty");
  wall.replaceChildren();

  if (!Array.isArray(steps) || steps.length === 0) {
    empty.hidden = false;
    return;
  }

  empty.hidden = true;
  steps.forEach((step) => {
    if (!step || typeof step.content !== "string") return;

    const article = document.createElement("article");
    article.className = "public-step";

    const meta = document.createElement("div");
    meta.className = "step-meta";
    const voice = document.createElement("span");
    voice.className = "voice-label";
    voice.textContent = copy[language].voiceLabel;
    const label = document.createElement("span");
    label.className = "step-language";
    label.textContent = step.language === "fa" ? "FA" : "EN";
    meta.append(voice, label);

    const quote = document.createElement("blockquote");
    quote.dir = step.language === "fa" ? "rtl" : "ltr";
    quote.textContent = step.content;

    article.append(meta, quote);

    if (Array.isArray(step.replies) && step.replies.length) {
      const replies = document.createElement("div");
      replies.className = "step-replies";
      const heading = document.createElement("h3");
      heading.className = "replies-title";
      heading.textContent = copy[language].replyLabel;
      replies.append(heading);
      step.replies.forEach((reply) => {
        if (!reply || typeof reply.content !== "string") return;
        const item = document.createElement("p");
        item.className = "step-reply";
        item.dir = reply.language === "en" ? "ltr" : "rtl";
        item.textContent = reply.content;
        replies.append(item);
      });
      if (replies.childElementCount > 1) article.append(replies);
    }

    wall.append(article);
  });

  if (!wall.childElementCount) empty.hidden = false;
}

fetch("./steps.json", { cache: "no-store" })
  .then((response) => {
    if (!response.ok) throw new Error("Steps unavailable");
    return response.json();
  })
  .then((data) => renderSteps(data.steps))
  .catch(() => renderSteps([]));

